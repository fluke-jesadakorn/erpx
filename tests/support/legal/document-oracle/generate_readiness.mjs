// Development-only import of small, owned synthetic operational probe inputs.
// The worker embeds bytes, never loads the conformance fixture tree at runtime.
import fs from 'node:fs';
import crypto from 'node:crypto';
const root='fixtures/legal/documents/';
const native=JSON.parse(fs.readFileSync(root+'native-conformance.v1.json','utf8'));
const docx=JSON.parse(fs.readFileSync(root+'docx-conformance.v1.json','utf8'));
const profiles=native.cases.filter(item=>!item.expected.error).map(item=>({label:item.id,mime:item.mediaType,hex:item.hex,method:{'pdf-text':'PdfText','image-ocr':'ImageOcr','pdf-ocr':'PdfOcr'}[item.expected.method],pages:item.expected.pages.length}));
profiles.push({label:'docx',mime:'application/vnd.openxmlformats-officedocument.wordprocessingml.document',hex:docx.cases[0].docxHex,method:'DocxText',pages:1});
const media={'application/pdf':'Pdf','image/png':'Png','image/jpeg':'Jpeg','application/vnd.openxmlformats-officedocument.wordprocessingml.document':'Docx'};
const hashes=['native-conformance.v1.json','docx-conformance.v1.json'].map(name=>`${name} SHA256 ${crypto.createHash('sha256').update(fs.readFileSync(root+name)).digest('hex')}`);
const source=`// Synthetic operational probes generated by generate_readiness.mjs.
// ${hashes.join('\n// ')}
use crate::domain::document_extraction::{LegalDocumentMediaType,ExtractionMethod};
pub(super) struct Probe {pub label:&'static str,pub media_type:LegalDocumentMediaType,pub hex:&'static str,pub method:ExtractionMethod,pub pages:usize}
#[rustfmt::skip]
pub(super) const PROBES:&[Probe]=&[
${profiles.map(item=>`    Probe{label:${JSON.stringify(item.label)},media_type:LegalDocumentMediaType::${media[item.mime]},hex:${JSON.stringify(item.hex)},method:ExtractionMethod::${item.method},pages:${item.pages}},`).join('\n')}
];
`;
fs.mkdirSync('packages/server-legal/src/adapters/document_readiness',{recursive:true});
fs.writeFileSync('packages/server-legal/src/adapters/document_readiness/probes.rs',source);
console.log(`Imported ${profiles.length} synthetic worker readiness inputs`);

import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { Pool } from 'pg';
import type { EngineeringMoneyPeopleBrowser } from '../../../fixtures/finance/builders/engineering-money-people-browser';

test('Learn workspace signs in through Account and preserves its isolated drawer draft', async ({ page, context }, info) => {
  test.setTimeout(180_000);
  const run = process.env.ERPX_DEMO_RUN;
  expect(process.env.ERPX_BROWSER_EXECUTION_MODE).toBe('development-smoke');
  expect(process.env.ERPX_DEVELOPMENT_HOST_LEASE).toBeTruthy();
  expect(run).toMatch(/^[a-f0-9]{12}$/);
  const directory = join(process.cwd(), '.runtime/browser', run!);
  const fixture = JSON.parse(await readFile(join(directory, 'engineering-money-people.json'), 'utf8')) as EngineeringMoneyPeopleBrowser;
  expect(fixture.run).toBe(run);
  const company = fixture.companies[info.project.name], user = company.users.learner;
  const origin = 'https://learn-dev-erpx.jesadakorn.com';
  const target = `${user.workspaceBase}/knowledge/learning/assignments/${company.learning.assignmentId}?workspaceSmoke=preserved`;
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const login = await page.goto(origin + target, { timeout: 120_000 });
  expect(new URL(page.url()).origin).toBe('https://account-dev-erpx.jesadakorn.com');
  expect(login?.headers()['x-erpx-app']).toBe('account');
  await page.getByRole('textbox', { name: 'Work email', exact: true }).fill(user.email);
  await page.locator('input[name="password"]').fill(fixture.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL(url => url.origin === origin && !url.pathname.startsWith('/sso/'), { timeout: 90_000 });
  const startForm = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Start course', exact: true }) });
  await expect(startForm).toBeVisible({ timeout: 90_000 });
  expect(new URL(page.url()).searchParams.get('workspaceSmoke')).toBe('preserved');
  for (const key of ['code', 'state', 'token', 'session_token']) expect(new URL(page.url()).searchParams.has(key)).toBe(false);
  await startForm.locator('[name="reason"]').fill('Fictional Learn workspace smoke begins its published course.');
  const starting = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/v1/holdings/simulation/learning');
  await startForm.getByRole('button', { name: 'Start', exact: true }).click();
  expect((await starting).status()).toBe(200);
  const trigger = page.locator('summary').filter({ hasText: /^Record attendance and result$/ });
  await trigger.click();
  const drawer = page.getByRole('dialog', { name: 'Record attendance and result', exact: true });
  await expect(drawer).toBeVisible();
  const box = await drawer.boundingBox(), viewport = page.viewportSize()!;
  expect(box).not.toBeNull();
  expect(Math.abs(box!.x + box!.width - viewport.width)).toBeLessThan(2);
  if(viewport.width>640)expect(box!.x).toBeGreaterThan(viewport.width * 0.2);
  else expect(Math.abs(box!.x)).toBeLessThan(2);
  const reason = drawer.locator('[name="reason"]');
  await reason.fill('Unsaved synthetic assessment draft.');
  await reason.press('Escape');
  const confirmation = page.getByRole('dialog', { name: 'Discard changes?', exact: true });
  await expect(confirmation).toBeVisible();
  await confirmation.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(reason).toHaveValue('Unsaved synthetic assessment draft.');
  await info.attach('Learn right drawer retains its draft', { body: await page.screenshot(), contentType: 'image/png' });
  await reason.press('Escape');
  await confirmation.getByRole('button', { name: 'Discard draft', exact: true }).click();
  await expect(drawer).toBeHidden();
  const refreshed = await page.reload();
  await expect(trigger).toBeVisible({ timeout: 60_000 });
  expect(refreshed?.status()).toBe(200);
  expect(refreshed?.headers()['x-erpx-app']).toBe('learn');
  const cookies = await context.cookies();
  expect(cookies.some(cookie => cookie.name === '__Host-erpx-product' && cookie.domain === 'learn-dev-erpx.jesadakorn.com')).toBe(true);
  expect(cookies.some(cookie => cookie.name === '__Secure-erpx-account.session_token' && cookie.domain === 'account-dev-erpx.jesadakorn.com')).toBe(true);
  for (const cookie of cookies) expect({ parentDomain: cookie.domain.startsWith('.'), secure: cookie.secure, httpOnly: cookie.httpOnly }).toEqual({ parentDomain: false, secure: true, httpOnly: true });
  const manifest = JSON.parse(await readFile(join(directory, 'databases.json'), 'utf8')), connection = new URL(manifest.databases.H001_DB);
  expect([connection.hostname, connection.port, connection.username, connection.pathname]).toEqual(['127.0.0.1', '5432', 'erpx_test_admin', `/erpx_browser_${run}_h001_db`]);
  const db = new Pool({ connectionString: connection.href, max: 1 });
  try {
    const rows = (await db.query('SELECT status,version FROM learning_assignments WHERE company_id=$1 AND id=$2', [company.companyId, company.learning.assignmentId])).rows;
    expect(rows).toHaveLength(1);
    expect(rows[0].status).toBe('in_progress');
    expect(Number(rows[0].version)).toBe(2);
  } finally { await db.end(); }
  expect(errors).toEqual([]);
});

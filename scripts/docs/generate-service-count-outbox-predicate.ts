import {readFile,writeFile} from 'node:fs/promises';
const root='packages/server-inventory/src/public/';
const [eligible,quarantine,ambiguous]=await Promise.all(['service_count_outbox_eligible.sql','service_count_outbox_quarantine.sql','service_count_outbox_ambiguous.sql'].map(path=>readFile(root+path,'utf8')));
// r43: the service-count marker guard is byte-identical in the quarantine and
// ambiguous outbox predicates. Emit it once and interpolate it into both so
// each predicate's runtime text stays byte-identical while only one marker
// literal remains. Locks, native transport and r11-r42 helpers stay untouched.
const markerStart='    EXISTS (SELECT 1 FROM inventory_service_initial_physical_sources s WHERE s.count_id=e.aggregate_id)';
const markerEnd="_serviceInitialPhysicalStockCount')))";
const from=quarantine.indexOf(markerStart),to=quarantine.indexOf(markerEnd,from);
if(from<0||to<0)throw Error('SERVICE_COUNT_MARKER_NOT_FOUND');
const marker=quarantine.slice(from,to+markerEnd.length);
if(!ambiguous.includes(marker))throw Error('SERVICE_COUNT_MARKER_DRIFT');
const token='@@SERVICE_COUNT_MARKER@@',shared='serviceCountMarkerPredicate';
const render=(sql:string)=>{
  const quoted=JSON.stringify(sql.replace(marker,token));
  return '`'+quoted.slice(1,-1).replace(token,'${'+shared+'}')+'`';
};
const output=`// Generated by scripts/docs/generate-service-count-outbox-predicate.ts; do not edit.\nexport const ${shared} = ${JSON.stringify(marker)};\nexport const serviceCountOutboxEligible = ${JSON.stringify(eligible)};\nexport const serviceCountOutboxQuarantine = ${render(quarantine)};\nexport const serviceCountOutboxAmbiguous = ${render(ambiguous)};\n`;
const destination=root+'service-count-outbox-predicate.generated.ts';
if(process.argv.includes('--check')){if(await readFile(destination,'utf8')!==output)throw new Error('SERVICE_COUNT_OUTBOX_PREDICATE_DRIFT');}
else await writeFile(destination,output);

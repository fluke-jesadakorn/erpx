
import { workFetch } from "@/lib/work-fetch";
import { prepareDocumentPages } from "./document-pages";
import {
  attachmentStatus,
  bindRecordAttachmentSet,
} from "./attachment-client";

export const receiptTypes = ["image/jpeg", "image/png", "image/webp", "application/pdf"];
export function validateReceipt(file: File, allowCsv = false) {
  if (!file.size || file.size > 10 * 1024 * 1024) throw Error("Choose a receipt up to 10 MB.");
  if (![...receiptTypes, ...(allowCsv ? ["text/csv"] : [])].includes(file.type))
    throw Error("Choose a JPG, PNG, WebP or PDF receipt.");
}
/** Retain each upload intent across retries, including a completed original whose pages failed. */
export function createReceiptUploader() {
  const attempts = new WeakMap<File, {
    url: string;
    key: string;
    attachmentSetId?: string;
    attachmentLinkId?: string;
    expectedTargetVersion?: number;
    original?: { id: string; checksum: string };
    done?: boolean;
  }>();
  return async (base: string, ownerId: string, file: File, payment = false, progress: (text: string) => void = () => {}) => {
    validateReceipt(file, !payment);
    let attempt = attempts.get(file);
    if (!attempt) {
      progress(`Uploading ${file.name}…`);
      const key = crypto.randomUUID();
      const response = await workFetch(`/api/v1${base}/uploads`, {
        method: "POST", headers: { "Content-Type": "application/json", "Idempotency-Key": key },
        body: JSON.stringify({ ownerType: payment ? "expense_payment" : "expense_claim", ownerId,
          purpose: payment ? "payment_slip" : "merchant_receipt", filename: file.name, mediaType: file.type, bytes: file.size }),
      });
      const result = await response.json();
      if (!response.ok) throw Error(result.error?.message ?? "Unable to prepare upload.");
      attempt = {
        url: result.data.uploadUrl,
        key,
        attachmentSetId: result.data.attachmentSetId,
        attachmentLinkId: result.data.attachmentLinkId,
        expectedTargetVersion: result.data.expectedTargetVersion,
      };
      attempts.set(file, attempt);
    }
    if (!attempt.original) {
      const response = await workFetch(attempt.url, { method: "PUT", headers: { "Content-Type": file.type }, body: file });
      const result = await response.json();
      if (!response.ok) throw Error(result.error?.message ?? "Unable to upload receipt.");
      if (result.data.attachmentLinkId) {
        attempt.attachmentLinkId = result.data.attachmentLinkId;
        let sourceId =
          result.data.state === "available" && result.data.sourceId
            ? String(result.data.sourceId)
            : null;
        if (!sourceId) {
          progress(`Scanning ${file.name}…`);
          let status: Awaited<ReturnType<typeof attachmentStatus>> | null = null;
          for (let scanAttempt = 0; scanAttempt < 120; scanAttempt += 1) {
            status = await attachmentStatus(base, result.data.attachmentLinkId);
            if (status.sourceState === "available") break;
            if (["malware_rejected", "scan_error", "destroyed"].includes(status.sourceState ?? ""))
              throw Error(
                status.sourceState === "malware_rejected"
                  ? "This file was rejected by malware scanning."
                  : status.scan.lastError ?? "This file could not be scanned.",
              );
            await new Promise((resolve) => setTimeout(resolve, 750));
          }
          if (status?.sourceState !== "available" || !status.sourceId)
            throw Error("The receipt scan is still pending. Try again shortly.");
          sourceId = status.sourceId;
        }
        if (payment) {
          attempt.original = { id: sourceId, checksum: "" };
          // Payment evidence is bound atomically by the save/confirm command.
          // Its canonical preview is generated by the scanner, so no client
          // derivative is needed.
          attempt.done = true;
        } else {
          if (!attempt.attachmentSetId || !attempt.expectedTargetVersion)
            throw Error("The receipt reservation is incomplete. Retry the upload.");
          progress(`Saving ${file.name}…`);
          const bound = await bindRecordAttachmentSet(
            base,
            attempt.attachmentSetId,
            attempt.expectedTargetVersion,
            `${attempt.key}:bind`,
          );
          const item = bound.manifest.find((entry) => entry.linkId === result.data.attachmentLinkId) ?? bound.manifest[0];
          if (!item) throw Error("The receipt was scanned but could not be linked.");
          attempt.original = { id: item.sourceId, checksum: item.checksumSha256 };
        }
      } else {
        attempt.original = { id: result.data.id, checksum: result.data.checksum };
      }
    }
    const original = attempt.original;
    if (!attempt.done) {
      try {
        await prepareDocumentPages(file, async (page, total, image) => {
          progress(`Preparing ${file.name} · page ${page} of ${total}…`);
          const response = await workFetch(`/api/v1${base}/attachments/${original.id}/derivatives?page=${page}&total=${total}&original=${original.checksum}`, {
            method: "POST", headers: { "Content-Type": "image/jpeg", "Idempotency-Key": `render-${original.id}-${page}` }, body: image,
          });
          const result = await response.json();
          if (!response.ok) throw Error(result.error?.message ?? "Unable to prepare this page.");
        });
        attempt.done = true;
      } catch (error) {
        throw Error(`The original receipt is saved. ${error instanceof Error ? error.message : "Unable to read this document."}`);
      }
    }
    return original;
  };
}

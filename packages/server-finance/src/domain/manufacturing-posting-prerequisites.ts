export const manufacturingPostingPeriodSchema=z.object({...initial,input:createPeriodSchema.strict()}).strict();
export const manufacturingPostingRateSchema=z.object({...initial,input:manualRateSchema.strict()}).strict();
export type ManufacturingPostingChartInput=z.infer<typeof manufacturingPostingChartSchema>;
export type ManufacturingPostingAccountInput=z.infer<typeof manufacturingPostingAccountSchema>;
export type ManufacturingPostingPeriodInput=z.infer<typeof manufacturingPostingPeriodSchema>;
export type ManufacturingPostingRateInput=z.infer<typeof manufacturingPostingRateSchema>;
export type ManufacturingPostingPrerequisitesView=SupplyPostingPrerequisitesView & {functionalCurrency:'THB';unsupportedExistingMapping:boolean};
